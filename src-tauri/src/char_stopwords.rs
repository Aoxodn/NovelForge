/// 对单字名返回内置误判词（空 vec 表示该字无内置词典）
pub fn default_exclude_for(name: &str) -> Vec<String> {
    if name.chars().count() != 1 {
        return Vec::new();
    }
    builtin_exclude_words()
        .get(name)
        .map(|arr| arr.iter().map(|s| s.to_string()).collect())
        .unwrap_or_default()
}
